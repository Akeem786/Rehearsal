"""Data models for Rehearsal deterministic evaluation suite and reporting."""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class EvaluationCase(BaseModel):
    """An individual test utterance case with ground-truth expectations."""
    id: str = Field(..., description="Unique case identifier, e.g., 'wx_01'")
    domain: str = Field(..., description="Domain name (e.g., 'weather', 'smart_home', 'travel')")
    utterance: str = Field(..., description="Spoken natural-language user query")
    expected_tool: Optional[str] = Field(None, description="Expected MCP tool name, or None if abstention")
    expected_arguments: Dict[str, Any] = Field(default_factory=dict, description="Expected arguments dict")
    rationale: str = Field(..., description="Human-readable justification for the expected outcome")
    is_ambiguous: bool = Field(default=False, description="Whether the request is intentionally underspecified")
    should_abstain: bool = Field(default=False, description="Whether the assistant should abstain from tool call")


class PredictionResult(BaseModel):
    """Independent prediction generated by the evaluation matcher."""
    predicted_tool: Optional[str] = Field(None, description="Predicted tool name, or None if abstention")
    predicted_arguments: Dict[str, Any] = Field(default_factory=dict, description="Extracted parameter arguments")
    is_abstention: bool = Field(default=False, description="Whether the matcher decided to abstain")
    clarification_prompt: Optional[str] = Field(None, description="Suggested recovery question for user")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Heuristic prediction confidence")


class CaseEvaluationResult(BaseModel):
    """Evaluation score and diagnostic breakdown for a single test case."""
    case_id: str
    domain: str
    utterance: str
    expected_tool: Optional[str]
    predicted_tool: Optional[str]
    tool_match: bool
    expected_arguments: Dict[str, Any]
    predicted_arguments: Dict[str, Any]
    exact_argument_match: bool
    matched_slots: List[str] = Field(default_factory=list)
    missing_slots: List[str] = Field(default_factory=list)
    unexpected_slots: List[str] = Field(default_factory=list)
    is_abstention_correct: bool = True
    tool_output: Optional[str] = None
    estimated_speech_duration_seconds: Optional[float] = None
    status: str = Field(default="PASS", description="'PASS' or 'FAIL'")


class SlotMetrics(BaseModel):
    """Precision, recall, and F1 score for slot/argument extraction."""
    total_expected_slots: int = 0
    total_predicted_slots: int = 0
    true_positives: int = 0
    precision: float = 0.0
    recall: float = 0.0
    f1_score: float = 0.0


class DomainEvaluationResult(BaseModel):
    """Summary metrics broken down by individual domain."""
    domain: str
    total_cases: int
    correct_tool_selections: int
    tool_selection_accuracy: float
    exact_argument_matches: int
    exact_argument_match_rate: float


class EvaluationReport(BaseModel):
    """Comprehensive evaluation report summarizing test suite execution."""
    total_cases: int
    correct_tool_selections: int
    tool_selection_accuracy: float
    exact_argument_matches: int
    exact_argument_match_rate: float
    slot_metrics: SlotMetrics
    missing_argument_count: int
    unexpected_argument_count: int
    total_abstentions: int
    correct_abstentions: int
    average_estimated_speech_duration_seconds: float = 0.0
    per_domain_results: Dict[str, DomainEvaluationResult] = Field(default_factory=dict)
    case_results: List[CaseEvaluationResult] = Field(default_factory=list)

    def to_json(self, indent: int = 2) -> str:
        """Serialize report to formatted JSON string."""
        return self.model_dump_json(indent=indent)

    def to_terminal_summary(self) -> str:
        """Render a clean, human-readable terminal dashboard table."""
        lines = [
            "=" * 72,
            "                   REHEARSAL EVALUATION SUITE REPORT",
            "=" * 72,
            f"Total Test Cases Analyzed:      {self.total_cases}",
            f"Tool Selection Accuracy:         {self.tool_selection_accuracy:.1%} ({self.correct_tool_selections}/{self.total_cases})",
            f"Exact Argument Match Rate:       {self.exact_argument_match_rate:.1%} ({self.exact_argument_matches}/{self.total_cases})",
            f"Slot Extraction F1 Score:        {self.slot_metrics.f1_score:.3f} (P: {self.slot_metrics.precision:.2f}, R: {self.slot_metrics.recall:.2f})",
            f"Missing Arguments Count:         {self.missing_argument_count}",
            f"Unexpected Arguments Count:      {self.unexpected_argument_count}",
            f"Abstentions / Clarifications:    {self.total_abstentions} (Correct: {self.correct_abstentions})",
            f"Avg Spoken Response Duration:    {self.average_estimated_speech_duration_seconds:.1f}s",
            "-" * 72,
            "Domain Breakdown:",
        ]
        for dom, res in self.per_domain_results.items():
            lines.append(
                f"  * {dom.ljust(14)}: Tool Acc: {res.tool_selection_accuracy:.1%} | "
                f"Arg Match: {res.exact_argument_match_rate:.1%} ({res.total_cases} cases)"
            )
        lines.append("=" * 72)
        return "\n".join(lines)
